#!/usr/bin/env python3
"""Prepare public math datasets in verl's chat/parquet schema; no model loading.

AIME prompts are stored once. Sixteen completions are generated by val_kwargs.n.
The public download path is not claimed to reconstruct an unidentified original
parquet byte-for-byte. Existing prepared files are accepted through CLI options.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

PROMPT_SUFFIX = "Please reason step by step, and put your final answer within \\boxed{}."


def normalize(row, index: int, *, source: str, split: str):
    if isinstance(row.get("prompt"), list) and row.get("reward_model", {}).get("ground_truth") is not None:
        prompt = row["prompt"]
        answer = row["reward_model"]["ground_truth"]
    else:
        question = next((row[k] for k in ("Problem", "problem", "question", "prompt") if isinstance(row.get(k), str)), None)
        answer = next((row[k] for k in ("Answer", "answer", "solution") if row.get(k) is not None), None)
        if question is None or answer is None:
            raise ValueError(f"Unsupported schema for {source}; provide prepared verl parquet instead.")
        prompt = [{"role": "user", "content": question.strip() + "\n\n" + PROMPT_SUFFIX}]
    return {
        "data_source": source,
        "prompt": prompt,
        "ability": "math",
        "reward_model": {"style": "rule", "ground_truth": str(answer)},
        "extra_info": {"split": split, "index": index},
    }


def main() -> None:
    from datasets import Dataset, load_dataset
    from huggingface_hub import HfApi

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "recipe/data/math_reasoning_parquet")
    parser.add_argument("--dapo-file", type=Path)
    parser.add_argument("--aime24-file", type=Path)
    parser.add_argument("--aime25-file", type=Path)
    parser.add_argument("--aime26-file", type=Path, help="Optional prepared public AIME26 parquet; no guessed source is used.")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    specs = [
        ("dapo_math_17k", "BytedTsinghua-SIA/DAPO-Math-17k", "train", args.dapo_file, "train"),
        ("aime24", "Maxwell-Jia/AIME_2024", "train", args.aime24_file, "test"),
        ("aime25", "yentinglin/aime_2025", "train", args.aime25_file, "test"),
    ]
    if args.aime26_file:
        specs.append(("aime26", None, "train", args.aime26_file, "test"))
    args.output_dir.mkdir(parents=True, exist_ok=True)
    manifest = {}
    api = HfApi()
    for name, repo, upstream_split, local, split in specs:
        dest = args.output_dir / f"{name}.parquet"
        if dest.exists() and not args.overwrite:
            raise FileExistsError(f"Refusing to replace {dest}; use --overwrite intentionally.")
        if local:
            ds = load_dataset("parquet", data_files=str(local), split="train")
            provenance = {"kind": "local", "filename": local.name, "sha256": hashlib.sha256(local.read_bytes()).hexdigest()}
        else:
            revision = api.dataset_info(repo).sha
            ds = load_dataset(repo, revision=revision, split=upstream_split)
            provenance = {"kind": "public_hub", "repository": repo, "revision": revision, "split": upstream_split}
        rows = [normalize(row, i, source=name, split=split) for i, row in enumerate(ds)]
        if split == "test":
            keys = [json.dumps(row["prompt"], sort_keys=True, ensure_ascii=False) for row in rows]
            if len(keys) != len(set(keys)):
                raise ValueError(f"{name} repeats validation questions; remove repetitions before avg@16 evaluation.")
        Dataset.from_list(rows).to_parquet(str(dest))
        provenance.update({"rows": len(rows), "sha256": hashlib.sha256(dest.read_bytes()).hexdigest()})
        manifest[name] = provenance
        print(f"Prepared {name}: {len(rows)} prompts")
    (args.output_dir / "data.lock.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
